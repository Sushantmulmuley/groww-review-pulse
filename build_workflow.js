'use strict';
/*
 * Generates the two importable n8n workflows from the real source files:
 *   n8n/review-pulse-main.json   - reviews -> insights -> pulse + explainer -> approval -> MCP actions
 *   n8n/mcp-server.json          - MCP Server Trigger exposing append_to_doc and create_email_draft
 * Run: node build_workflow.js
 * The Code nodes contain code/lib.js verbatim plus the BANK (data/fee_facts.json), so what runs in n8n
 * is exactly what tests/ run in Node.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = __dirname;
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const lib = read('code/lib.js').replace(/\/\/ ---- exports[\s\S]*$/, '');
const bank = JSON.stringify(JSON.parse(read('data/fee_facts.json')));
const P1 = read('prompts/1_themes_quotes_fee.system.md').trim();
const P2 = read('prompts/2_pulse_and_explainer.system.md').trim();
const P3 = read('prompts/3_agent.system.md').trim();

const uuid = (s) => { const h = crypto.createHash('sha1').update('groww-review-pulse:' + s).digest('hex'); return [h.slice(0, 8), h.slice(8, 12), '5' + h.slice(13, 16), '8' + h.slice(17, 20), h.slice(20, 32)].join('-'); };
const header = '// Generated by build_workflow.js. Source: code/lib.js + data/fee_facts.json\n' + lib + '\nconst BANK = ' + bank + ';\n';

const TAIL = {};
TAIL.clean = `
const cfg = $('Config').first().json;
const rows = $input.all().map(function (i) { return i.json; });
const cleaned = cleanReviews(rows, { windowWeeks: Number(cfg.windowWeeks) || 12 });
const reviews = cleaned.reviews, stats = cleaned.stats;
if (reviews.length < 50) throw new Error('Only ' + reviews.length + ' usable reviews after cleaning; at least 50 are needed.');
const sample = stratifiedSample(reviews, Number(cfg.sampleSize) || 150, 17);
const table = feeTable(reviews, Object.keys(BANK.entries), stats.date_to);
const feeBlock = table.map(function (t) {
  return 'id=' + t.id + ' | named=' + t.named + ' | said unexpected or unclear=' + t.confused + ' | rate=' + t.confusion_rate_pct + '%\\n' +
    t.evidence.map(function (e) { return '   ' + e.id + ' | ' + e.rating + '* | ' + e.text; }).join('\\n');
}).join('\\n');
const prompt = 'STATS: ' + JSON.stringify({ reviews: stats.kept, from: stats.date_from, to: stats.date_to, avg_rating: stats.avg_rating, one_two_star_pct: stats.low_star_pct }) +
  '\\n\\nSAMPLE (' + sample.length + ' reviews, format: id | stars | text):\\n' + contextLines(sample, 260) +
  '\\n\\nFEE CANDIDATES (counted by code over all ' + stats.kept + ' reviews; evidence lines are real reviews):\\n' + feeBlock;
return [{ json: { stats: stats, reviews: reviews, prompt: prompt } }];
`;
TAIL.insights = `
const src = $('Clean and retrieve').first().json;
let llm = null, parseNote = null;
try { llm = repairJson($input.first().json.text); } catch (e) { parseNote = 'model output unreadable (' + e.message + '); default themes used'; }
const ins = buildInsights(llm, src.reviews, BANK, { stats: src.stats, runDate: $now.toISODate() });
if (parseNote) ins.flags.unshift(parseNote);
const entry = BANK.entries[ins.fee_issue.id];
const brief = {
  scope: { reviews: ins.scope.kept, from: ins.scope.date_from, to: ins.scope.date_to, avg_rating: ins.scope.avg_rating },
  top_themes: ins.top_themes,
  quotes: ins.quotes.map(function (q) { return { text: q.text, stars: q.rating }; }),
  fee_issue: { name: ins.fee_issue.name, named: ins.fee_issue.named, said_unexpected_or_unclear: ins.fee_issue.confused, rate_pct: ins.fee_issue.confusion_rate_pct, trend: ins.fee_issue.trend, summary: ins.fee_issue.summary }
};
const prompt2 = 'INSIGHTS (counted by code; use only these figures):\\n' + JSON.stringify(brief) +
  '\\n\\nFACTS about ' + entry.name + ' (official Groww pages, last checked ' + BANK.last_checked + '):\\n' +
  entry.facts.map(function (f, i) { return (i + 1) + '. ' + f; }).join('\\n');
return [{ json: { insights: ins, prompt2: prompt2 } }];
`;
TAIL.outputs = `
const ins = $('Check insights').first().json.insights;
let m = {}, note = null;
try { m = repairJson($input.first().json.text); } catch (e) { note = 'writer output unreadable; text built by code from the counted insights and the fact bank'; }
const pulse = assemblePulse(ins, { observation: m.observation, actions: m.actions });
const expl = assembleExplainer(ins.fee_issue.id, BANK, m.explainer_bullets);
const payload = buildPayload(ins, pulse, expl);
const flags = [].concat(note ? [note] : [], ins.flags, pulse.flags, expl.flags);
const checks = [
  'weekly pulse: ' + pulse.words + ' of 250 words',
  'fee explainer: ' + expl.bullets.length + ' bullets (max 6), ' + expl.links.length + ' official links, last checked ' + expl.last_checked,
  'quotes verified word for word against real reviews: ' + ins.quotes.length + ' of 3'
];
const approval_text = [
  'Nothing has been written or drafted yet. If you approve, two actions run and nothing is sent:',
  '1. Append the log entry (same content as below) to the product log Google Doc.',
  '2. Create a Gmail draft with the subject: ' + payload.email.subject,
  '',
  'Automatic checks: ' + checks.join('; ') + '.',
  flags.length ? 'Notes: ' + flags.join('; ') + '.' : 'Notes: none.',
  '',
  '----- WEEKLY PULSE -----',
  pulse.markdown,
  '',
  '----- FEE EXPLAINER -----',
  expl.markdown
].join('\\n');
return [{ json: { payload: payload, doc_entry: buildDocEntry(payload.entry), approval_text: approval_text, checks: checks, flags: flags, pulse_words: pulse.words } }];
`;
TAIL.mcp = `
const o = $('Check outputs').first().json;
const cfg = $('Config').first().json;
const prompt = [
  'The reviewer has approved. Make exactly two tool calls, in this order, then stop.',
  '',
  'CALL 1: the append_to_doc tool. Set text to the DOC ENTRY below, character for character.',
  'CALL 2: the create_email_draft tool. Set to = ' + cfg.draftTo + ', subject = ' + o.payload.email.subject + ', message = the EMAIL BODY below, character for character.',
  '',
  '(Tool names may carry an MCP_Client_ prefix.) Do not send anything. Do not edit, summarise or reorder the text.',
  '',
  '<<<DOC ENTRY',
  o.doc_entry,
  'DOC ENTRY>>>',
  '',
  '<<<EMAIL BODY',
  o.payload.email.body,
  'EMAIL BODY>>>'
].join('\\n');
return [{ json: { prompt: prompt } }];
`;

const CRED_GEMINI = { googlePalmApi: { id: 'REPLACE_CRED_ID', name: 'Google Gemini(PaLM) Api account' } };
const CRED_GMAIL = { gmailOAuth2: { id: 'REPLACE_CRED_ID', name: 'Gmail account' } };
const CRED_DOCS = { googleDocsOAuth2Api: { id: 'REPLACE_CRED_ID', name: 'Google Docs account' } };

function node(name, type, typeVersion, position, parameters, extra) {
  return Object.assign({ id: uuid(name), name: name, type: type, typeVersion: typeVersion, position: position, parameters: parameters }, extra || {});
}
const code = (name, pos, tail) => node(name, 'n8n-nodes-base.code', 2, pos, { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: header + tail });
const gemini = (name, pos, temp) => node(name, '@n8n/n8n-nodes-langchain.lmChatGoogleGemini', 1.2, pos, { modelName: 'models/gemini-3.8-flash', options: { temperature: temp, maxOutputTokens: 16384 } }, { credentials: CRED_GEMINI });
const chain = (name, pos, textExpr, system) => node(name, '@n8n/n8n-nodes-langchain.chainLlm', 1.9, pos, {
  promptType: 'define', text: textExpr, hasOutputParser: false,
  messages: { messageValues: [{ type: 'SystemMessagePromptTemplate', message: system }] }, batching: {}
});
const main = (to) => ({ main: [[{ node: to, type: 'main', index: 0 }]] });

// ---------------- main workflow ----------------
const mainNodes = [
  node('Run weekly pulse', 'n8n-nodes-base.manualTrigger', 1, [0, 0], {}),
  node('Config', 'n8n-nodes-base.set', 3.5, [220, 0], {
    mode: 'manual', includeOtherFields: false,
    assignments: {
      assignments: [
        { id: uuid('cfg-csv'), name: 'csvUrl', value: 'https://raw.githubusercontent.com/REPLACE_GITHUB_USER/REPLACE_REPO/main/data/reviews.csv', type: 'string' },
        { id: uuid('cfg-win'), name: 'windowWeeks', value: 12, type: 'number' },
        { id: uuid('cfg-sample'), name: 'sampleSize', value: 150, type: 'number' },
        { id: uuid('cfg-approver'), name: 'approverEmail', value: 'REPLACE_WITH_YOUR_GMAIL', type: 'string' },
        { id: uuid('cfg-draft'), name: 'draftTo', value: 'REPLACE_WITH_DRAFT_RECIPIENT', type: 'string' }
      ]
    }, options: {}
  }),
  node('Fetch reviews CSV', 'n8n-nodes-base.httpRequest', 4.5, [440, 0], { method: 'GET', url: '={{ $json.csvUrl }}', options: { response: { response: { responseFormat: 'file', outputPropertyName: 'data' } } } }),
  node('Read CSV rows', 'n8n-nodes-base.extractFromFile', 1.2, [660, 0], { operation: 'csv', binaryPropertyName: 'data', options: { headerRow: true } }),
  code('Clean and retrieve', [880, 0], TAIL.clean),
  chain('Gemini: themes, quotes, fee', [1100, 0], '={{ $json.prompt }}', P1),
  gemini('Gemini model (analysis)', [1100, 240], 0.2),
  code('Check insights', [1320, 0], TAIL.insights),
  chain('Gemini: pulse and explainer', [1540, 0], '={{ $json.prompt2 }}', P2),
  gemini('Gemini model (writer)', [1540, 240], 0.3),
  code('Check outputs', [1760, 0], TAIL.outputs),
  node('Ask for approval', 'n8n-nodes-base.gmail', 2.2, [1980, 0], {
    authentication: 'oAuth2', resource: 'message', operation: 'sendAndWait',
    sendTo: "={{ $('Config').first().json.approverEmail }}",
    subject: "={{ 'APPROVE? ' + $json.payload.email.subject }}",
    message: '={{ $json.approval_text }}',
    responseType: 'approval',
    approvalOptions: { values: { approvalType: 'double', approveLabel: 'Approve and log', buttonApprovalStyle: 'primary', disapproveLabel: 'Reject', buttonDisapprovalStyle: 'secondary' } },
    options: { appendAttribution: false }
  }, { credentials: CRED_GMAIL, webhookId: uuid('webhook-approval') }),
  node('Approved?', 'n8n-nodes-base.if', 2.4, [2200, 0], {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 3 },
      conditions: [{ id: uuid('if-approved'), leftValue: '={{ $json.data.approved }}', rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
      combinator: 'and'
    }, options: {}
  }),
  code('Build MCP instructions', [2420, -120], TAIL.mcp),
  node('AI Agent (MCP)', '@n8n/n8n-nodes-langchain.agent', 3.1, [2640, -120], { promptType: 'define', text: '={{ $json.prompt }}', hasOutputParser: false, options: { systemMessage: P3, enableStreaming: false } }),
  gemini('Gemini model (agent)', [2640, 120], 0),
  node('MCP Client', '@n8n/n8n-nodes-langchain.mcpClientTool', 1.4, [2860, 120], { endpointUrl: 'REPLACE_WITH_YOUR_MCP_PRODUCTION_URL', serverTransport: 'httpStreamable', authentication: 'none', include: 'all', options: {} }),
  node('Logged', 'n8n-nodes-base.set', 3.5, [2860, -120], {
    mode: 'manual', includeOtherFields: false,
    assignments: { assignments: [
      { id: uuid('logged-status'), name: 'status', value: 'Approved: doc entry appended and Gmail draft created (not sent)', type: 'string' },
      { id: uuid('logged-agent'), name: 'agent_reply', value: '={{ $json.output }}', type: 'string' }
    ] }, options: {}
  }),
  node('Rejected', 'n8n-nodes-base.set', 3.5, [2420, 160], {
    mode: 'manual', includeOtherFields: false,
    assignments: { assignments: [{ id: uuid('rej-status'), name: 'status', value: 'Rejected: nothing was written and no draft was created', type: 'string' }] }, options: {}
  })
];
const mainConn = {
  'Run weekly pulse': main('Config'),
  'Config': main('Fetch reviews CSV'),
  'Fetch reviews CSV': main('Read CSV rows'),
  'Read CSV rows': main('Clean and retrieve'),
  'Clean and retrieve': main('Gemini: themes, quotes, fee'),
  'Gemini model (analysis)': { ai_languageModel: [[{ node: 'Gemini: themes, quotes, fee', type: 'ai_languageModel', index: 0 }]] },
  'Gemini: themes, quotes, fee': main('Check insights'),
  'Check insights': main('Gemini: pulse and explainer'),
  'Gemini model (writer)': { ai_languageModel: [[{ node: 'Gemini: pulse and explainer', type: 'ai_languageModel', index: 0 }]] },
  'Gemini: pulse and explainer': main('Check outputs'),
  'Check outputs': main('Ask for approval'),
  'Ask for approval': main('Approved?'),
  'Approved?': { main: [[{ node: 'Build MCP instructions', type: 'main', index: 0 }], [{ node: 'Rejected', type: 'main', index: 0 }]] },
  'Build MCP instructions': main('AI Agent (MCP)'),
  'Gemini model (agent)': { ai_languageModel: [[{ node: 'AI Agent (MCP)', type: 'ai_languageModel', index: 0 }]] },
  'MCP Client': { ai_tool: [[{ node: 'AI Agent (MCP)', type: 'ai_tool', index: 0 }]] },
  'AI Agent (MCP)': main('Logged')
};
// Google's Gemini API sometimes answers 503 (high demand). Retry the three model-calling nodes.
['Gemini: themes, quotes, fee', 'Gemini: pulse and explainer', 'AI Agent (MCP)'].forEach(function (n) {
  const nd = mainNodes.find(function (x) { return x.name === n; });
  nd.retryOnFail = true; nd.maxTries = 4; nd.waitBetweenTries = 5000;
});

const mainWf = { name: 'Review pulse: reviews to approved log and draft', nodes: mainNodes, connections: mainConn, pinData: {}, settings: { executionOrder: 'v1' }, active: false };

// ---------------- MCP server workflow ----------------
const serverNodes = [
  node('MCP Server Trigger', '@n8n/n8n-nodes-langchain.mcpTrigger', 2.1, [0, 0], { path: 'groww-review-pulse', authentication: 'none' }, { webhookId: uuid('webhook-mcp') }),
  node('append_to_doc', 'n8n-nodes-base.googleDocsTool', 2, [-240, 300], {
    descriptionType: 'manual',
    toolDescription: 'Append one weekly log entry to the end of the product log Google Doc. Pass the full entry text exactly as given.',
    authentication: 'oAuth2', resource: 'document', operation: 'update',
    documentURL: 'REPLACE_WITH_YOUR_GOOGLE_DOC_URL', simple: true,
    actionsUi: { actionFields: [{ object: 'text', action: 'insert', locationChoice: 'endOfSegmentLocation', insertSegment: 'body', text: "={{ $fromAI('text', 'The full log entry to append at the end of the document', 'string') }}" }] },
    updateFields: {}
  }, { credentials: CRED_DOCS }),
  node('create_email_draft', 'n8n-nodes-base.gmailTool', 2.2, [240, 300], {
    descriptionType: 'manual',
    toolDescription: 'Create a Gmail DRAFT email. This tool can only create a draft; it never sends.',
    resource: 'draft', operation: 'create',
    subject: "={{ $fromAI('subject', 'Email subject line', 'string') }}",
    emailType: 'text',
    message: "={{ $fromAI('message', 'Plain-text email body', 'string') }}",
    options: { sendTo: "={{ $fromAI('to', 'Recipient email address', 'string') }}" }
  }, { credentials: CRED_GMAIL })
];
const serverConn = {
  'append_to_doc': { ai_tool: [[{ node: 'MCP Server Trigger', type: 'ai_tool', index: 0 }]] },
  'create_email_draft': { ai_tool: [[{ node: 'MCP Server Trigger', type: 'ai_tool', index: 0 }]] }
};
const serverWf = { name: 'MCP server: append_to_doc and create_email_draft', nodes: serverNodes, connections: serverConn, pinData: {}, settings: { executionOrder: 'v1' }, active: false };

fs.mkdirSync(path.join(root, 'n8n'), { recursive: true });
fs.writeFileSync(path.join(root, 'n8n/review-pulse-main.json'), JSON.stringify(mainWf, null, 2));
fs.writeFileSync(path.join(root, 'n8n/mcp-server.json'), JSON.stringify(serverWf, null, 2));
console.log('wrote n8n/review-pulse-main.json (' + mainNodes.length + ' nodes) and n8n/mcp-server.json (' + serverNodes.length + ' nodes)');
